/**
 * The two font faces the stats image draws with, base64-encoded.
 *
 * **Why they are in source rather than read from disk.** Satori has no system
 * font — the default bundled with `next/og` is Geist, which has no Hangul, so
 * on a Korean-first app every label would render as blank boxes without these.
 * The documented way to load one is
 * `fetch(new URL('./font.ttf', import.meta.url))`, which relies on the bundler
 * rewriting that URL; under Turbopack in dev it resolves to a `file:` URL and
 * undici refuses it outright ("not implemented... yet..."). Reading with `fs`
 * works in dev but then depends on `outputFileTracingIncludes` being right, and
 * a missing font in production fails as a 500 on a route nobody exercises until
 * a user taps Share.
 *
 * Embedding sidesteps both. It is only affordable because these are **subset**
 * faces: Google Fonts' `text=` API was asked for exactly the glyphs the image
 * draws, which is ~20KB each rather than the ~5.7MB a full Noto Sans KR weight
 * would be.
 *
 * ⚠️ **Regenerate these if the image gains a character.** A glyph outside the
 * subset renders as nothing, *silently* — no error, no tofu box, just a gap.
 * Adding the language names on 2026-09-12 needed exactly this: the previous
 * subset held 53 glyphs and every language name in both locales fell outside
 * it. "Korean" wanted a `K` it did not have, and 한국어 had 한 but neither 국
 * nor 어.
 *
 * **How to regenerate.** The set is every `share*` and `label*` value in both
 * locales in `i18n.ts` (placeholders stripped — they are substituted before
 * they are drawn), plus what the render itself emits whatever the locale:
 * digits, `,` and `.` from `toLocaleString`, `%`, the `K` of `formatCount`,
 * the `·` and `+` of the language line. That came to 113 glyphs. Ask
 * `https://fonts.googleapis.com/css2?family=Noto+Sans+KR:wght@400&text=…` for
 * the CSS, then fetch the URL inside it.
 *
 * ⚠️ **The User-Agent decides the format, and only one of them is usable.**
 * A bare `Mozilla/5.0` gets raw TrueType, which is what these are (magic
 * `00010000`) and what satori reads. A modern browser UA gets WOFF; an MSIE
 * UA gets EOT, whose first four bytes are a little-endian file size and which
 * satori cannot parse at all. Check the magic before pasting anything in here,
 * and check the cmap covers every glyph you asked for.
 */

