/**
 * The two font faces the stats image draws with, base64-encoded.
 *
 * **Why they are in source rather than read from disk.** Satori has no system
 * font — the default bundled with `next/og` is Geist, which has no Hangul, so
 * on a Korean-first app every label would render as blank boxes without these.
 * The documented way to load one is
 * `fetch(new URL('./font.ttf', import.meta.url))`, which relies on the bundler
 * rewriting that URL; under Turbopack in dev it resolves to a `file:` URL and
 * undici refuses it outright ("not implemented... yet..."). Reading with `fs`
 * works in dev but then depends on `outputFileTracingIncludes` being right, and
 * a missing font in production fails as a 500 on a route nobody exercises until
 * a user taps Share.
 *
 * Embedding sidesteps both. It is only affordable because these are **subset**
 * faces: Google Fonts' `text=` API was asked for exactly the glyphs the image
 * draws, which is ~20KB each rather than the ~5.7MB a full Noto Sans KR weight
 * would be.
 *
 * ⚠️ **Regenerate these if the image gains a character**, and do not go by what
 * the rendered PNG looks like. A glyph outside the subset does *not* reliably
 * show as a gap: `ImageResponse` hands satori `loadDynamicAsset`, which detects
 * the script of any segment the given fonts cannot draw and downloads a face
 * for it from Google Fonts **at render time**. So a missing glyph usually still
 * appears — at the cost of turning a deterministic local render into a network
 * fetch on the share path, and of rendering as nothing the moment that fetch is
 * slow, blocked or offline. The gaps below were all found by reading the
 * `cmap`, never by looking at an image.
 *
 * Note also that a `fonts` option **replaces** the bundled Geist rather than
 * adding to it (`fonts: options.fonts || defaultFonts`), so Latin is no safer
 * here than Hangul — "Newly learned" was missing its `N` for exactly as long as
 * 「새로 익힘」 was missing three of its four.
 *
 * **How to regenerate.** The set is every value the *route* draws, in both
 * locales, with placeholders stripped — they are substituted before they are
 * drawn. That is `shareVariantToday`, `shareWindowDays`, `shareStatReviews`,
 * `shareStatStreak`, `shareStatMatured`, `shareStatTime`, the three
 * `shareTime*` formats, `shareFooter`, `progressStatNewCards` and
 * `progressChartWeeklyNote`, plus every `label*`; and what the render itself
 * emits whatever the locale: digits, `,` and `.` from `toLocaleString`, `%`,
 * the `K` of `formatCount`, the `·` and `+` of the language line. The chooser's
 * own strings — `shareTitle`, `shareChoose`, `shareBack`, `shareNothingYet`,
 * `shareFailed` — are deliberately **not** in it; they never reach a canvas.
 * That came to 137 glyphs (2026-09-23; 122 before, and nine of the fifteen
 * added were repairs rather than new work). Ask
 * `https://fonts.googleapis.com/css2?family=Noto+Sans+KR:wght@400&text=…` for
 * the CSS, then fetch the URL inside it.
 *
 * ⚠️ **Check both weights against the same set.** They are fetched separately,
 * and a glyph present at 400 and absent at 700 is a gap that only shows on a
 * bold label — which is every tile value and every hero figure.
 *
 * ⚠️ **The User-Agent decides the format, and only one of them is usable.**
 * A bare `Mozilla/5.0` gets raw TrueType, which is what these are (magic
 * `00010000`) and what satori reads. A modern browser UA gets WOFF; an MSIE
 * UA gets EOT, whose first four bytes are a little-endian file size and which
 * satori cannot parse at all. Check the magic before pasting anything in here,
 * and check the cmap covers every glyph you asked for.
 */

